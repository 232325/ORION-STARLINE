class PWAManager:
    """Asosiy PWA manager"""
    
    def __init__(self, project_root: str, config: PWAConfig):
        self.project_root = Path(project_root)
        self.config = config
        self.sw_config = self._create_sw_config()
        
        # PWA fayllar papkasi
        self.pwa_dir = self.project_root / "pwa_assets"
        self.pwa_dir.mkdir(exist_ok=True)
        
        # Service Worker generator
        self.sw_generator = ServiceWorkerGenerator(config, self.sw_config)
        
        # Manifest generator
        self.manifest_generator = WebAppManifest(config)

    def _create_sw_config(self) -> ServiceWorkerConfig:
        """Service Worker konfiguratsiya yaratish"""
        return ServiceWorkerConfig(
            cache_name=f"{self.config.cache_name}-{self.config.version}",
            precache_files=[
                "/",
                "/index.html",
                "/manifest.json",
                self.config.offline_page,
                "/icon-192x192.png",
                "/icon-512x512.png"
            ],
            runtime_cache_rules=[
                {
                    "urlPattern": r"^/api/.*",
                    "strategy": "network-first",
                    "cacheName": "api-cache",
                    "maxAge": 300  # 5 minutes
                },
                {
                    "urlPattern": r"^/assets/.*\.(js|css)$",
                    "strategy": "cache-first",
                    "cacheName": "static-cache",
                    "maxAge": 86400  # 1 day
                },
                {
                    "urlPattern": r"^/images/.*",
                    "strategy": "cache-first",
                    "cacheName": "images-cache",
                    "maxAge": 604800  # 1 week
                },
                {
                    "urlPattern": r"^/fonts/.*",
                    "strategy": "cache-first",
                    "cacheName": "fonts-cache",
                    "maxAge": 2592000  # 1 month
                }
            ],
            skip_waiting=True,
            clients_claim=True,
            enable_offline_fallback=True,
            enable_background_sync=self.config.enable_background_sync,
            network_first_timeout=3,
            cache_first_max_age=86400
        )

    async def setup_pwa(self) -> Dict:
        """PWA sozlamalarini o'rnatish"""
        logger.info("🚀 PWA sozlamalari o'rnatilmoqda...")
        
        try:
            # 1. Service Worker yaratish
            await self._create_service_worker()
            
            # 2. Web App Manifest yaratish
            await self._create_manifest()
            
            # 3. Icon'lar generatsiya qilish
            await self._generate_icons()
            
            # 4. Offline sahifa yaratish
            await self._create_offline_page()
            
            # 5. Push notification qo'llab-quvvatlash
            if self.config.enable_push:
                await self._setup_push_notifications()
            
            # 6. Background sync sozlamalari
            if self.config.enable_background_sync:
                await self._setup_background_sync()
            
            # 7. PWA metateglar qo'shish
            await self._add_pwa_meta_tags()
            
            # 8. Update system
            await self._setup_update_system()
            
            # 9. Installation prompt
            await self._setup_installation_prompt()
            
            # 10. Network detection
            await self._setup_network_detection()
            
            # 11. Test va validatsiya
            await self._validate_pwa()
            
            # 12. Hisobot yaratish
            await self._generate_pwa_report()
            
            logger.info("✅ PWA sozlamalari muvaffaqiyatli tugallandi!")
            return {"status": "success", "pwa_files": self._get_created_files()}
            
        except Exception as e:
            logger.error(f"❌ PWA sozlamalari xatosi: {str(e)}")
            raise

