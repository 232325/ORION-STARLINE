    async def _validate_manifest(self) -> Dict:
        """Manifest validatsiya"""
        manifest_path = self.project_root / "manifest.json"
        
        if not manifest_path.exists():
            return {"exists": False}
        
        try:
            async with aiofiles.open(manifest_path, 'r', encoding='utf-8') as f:
                content = await f.read()
                manifest = json.loads(content)
            
            required_fields = ["name", "short_name", "icons", "start_url", "display"]
            missing_fields = [field for field in required_fields if field not in manifest]
            
            return {
                "exists": True,
                "valid_json": True,
                "required_fields_present": len(missing_fields) == 0,
                "missing_fields": missing_fields,
                "fields_count": len(manifest)
            }
        except Exception as e:
            return {
                "exists": True,
                "valid_json": False,
                "error": str(e)
            }

