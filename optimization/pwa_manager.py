    def _get_created_files(self) -> List[str]:
        """Yaratilgan fayllar ro'yxati"""
        files = [
            "service-worker.js",
            "manifest.json",
            self.config.offline_page.lstrip('/'),
            "push-notification-manager.js",
            "background-sync.js",
            "update-manager.js",
            "install-prompt.js",
            "network-detector.js"
        ]
        
        return [str(self.project_root / f) for f in files if (self.project_root / f).exists()]

    def get_pwa_status(self) -> Dict:
        """PWA holatini olish"""
        sw_exists = (self.project_root / "service-worker.js").exists()
        manifest_exists = (self.project_root / "manifest.json").exists()
        offline_exists = (self.project_root / self.config.offline_page.lstrip('/')).exists()
        
        return {
            "service_worker_configured": sw_exists,
            "manifest_configured": manifest_exists,
            "offline_page_configured": offline_exists,
            "pwa_score": sum([sw_exists, manifest_exists, offline_exists]) / 3 * 100
        }

